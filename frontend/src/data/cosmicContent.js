export const getRecommendedSpread = ({ lifePath, zodiacDetails }) => {
  if (!lifePath && !zodiacDetails) {
    return {
      name: 'The Insight',
      reason: 'Một lá bài đủ nhẹ để bắt đầu khi bạn chưa có hồ sơ cá nhân.',
      path: '/tarot',
    };
  }

  if ([7, 9, 11, 22, 33].includes(lifePath)) {
    return {
      name: 'The Inner Compass',
      reason: 'Phù hợp với người cần đào sâu bài học nội tâm và phân biệt trực giác với nỗi sợ.',
      path: '/tarot',
    };
  }

  if (zodiacDetails?.element?.includes('Hỏa')) {
    return {
      name: 'The Crossroads',
      reason: 'Năng lượng Hỏa thường cần quyết định nhanh nhưng sáng suốt giữa hai hướng hành động.',
      path: '/tarot',
    };
  }

  return {
    name: 'The Flow of Time',
    reason: 'Ba lá Quá khứ - Hiện tại - Tương lai giúp bạn nhìn chu kỳ hiện tại rõ và mềm hơn.',
    path: '/tarot',
  };
};

export const buildCosmicInsights = ({ zodiacDetails, lifePath, destinyNumber, personalYear }) => {
  const insights = [];

  if (zodiacDetails) {
    insights.push(`${zodiacDetails.name.split(' (')[0]} mang nhịp ${zodiacDetails.element}, nên bản đồ của bạn bắt đầu từ cách bạn xử lý năng lượng ${zodiacDetails.vibe.toLowerCase()}.`);
  }

  if (lifePath) {
    const archetype = getNumberArchetype(lifePath);
    insights.push(`Life Path ${lifePath} nhấn mạnh bài học "${archetype.keyword}": ${archetype.lesson}`);
  }

  if (destinyNumber) {
    const archetype = getNumberArchetype(destinyNumber);
    insights.push(`Destiny Number ${destinyNumber} cho thấy cách bạn để lại dấu ấn qua phẩm chất "${archetype.keyword.toLowerCase()}".`);
  }

  if (personalYear) {
    const archetype = getNumberArchetype(personalYear);
    insights.push(`Năm cá nhân ${personalYear} mời bạn thực hành: ${archetype.action}`);
  }

  if (insights.length === 0) {
    return [
      'Bản đồ cá nhân sẽ rõ hơn khi bạn cập nhật tên và ngày sinh.',
      'Bạn vẫn có thể bắt đầu bằng một trải bài ngắn để nhận thông điệp hiện tại.',
      'Hãy xem hồ sơ như la bàn chiêm nghiệm, không phải khuôn mẫu cố định.',
    ];
  }

  return insights.slice(0, 4);
};

